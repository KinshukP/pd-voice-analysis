def ece(prob, truth, bins=10):
    total = 0.0
    for lo in np.linspace(0, 1, bins + 1)[:-1]:
        hi = lo + 1 / bins
        m = (prob >= lo) & (prob < hi)
        if m.sum():
            total += m.mean() * abs(truth[m].mean() - prob[m].mean())
    return total

