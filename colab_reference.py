def load_dataset():
    path = find_csv()
    raw = pd.read_csv(path, header=1)
    y = raw["class"].astype(int).values
    groups = ("PC:" + raw["id"].astype(str)).values
    X = raw.drop(columns=["id", "class"]).apply(pd.to_numeric, errors="coerce")
    X = X.fillna(X.median())
    feature_cols = list(X.columns)
    print(f"Loaded {path.name}: {len(X)} rows, {len(feature_cols)} features")
    sp = pd.Series(y, index=groups).groupby(level=0).first()
