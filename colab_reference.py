calibrator, THRESHOLD, LOW, HIGH = conf["calibrator"], conf["threshold"], conf["band_low"], conf["band_high"]


# Build Grounded Facts

def build_facts(i):
    raw = float(model.predict_proba(X.iloc[[i]])[0, 1])
    calibrated = float(calibrator.transform([raw])[0])
    band = "likely_pd" if calibrated > HIGH else ("likely_healthy" if calibrated < LOW else "uncertain")
    row = concept_contrib.iloc[i].sort_values(key=np.abs, ascending=False)
    factors = [
        {"concept": k.replace("_", " "), "direction": "toward PD" if v > 0 else "toward healthy", "weight": round(float(v), 2)}
        for k, v in row.items() if abs(v) >= MIN_FACTOR_WEIGHT
    ][:MAX_FACTORS]
    stated = round((calibrated if band != "likely_healthy" else 1 - calibrated) * 100)
    return {"band": band, "pd_probability": round(calibrated, 2), "stated_confidence_pct": stated, "top_factors": factors}


# Prompt For A Real LLM

def build_prompt(facts):
    return (
        "Write a 3-5 sentence plain-language explanation of a Parkinson's voice-SCREENING result for a general audience.\n"
        "RULES: Use ONLY the facts below. Do NOT invent or describe what any acoustic feature means beyond the plain labels given. "
        "Match tone to confidence. If band is likely_healthy, say 'no strong signs detected', never 'you are healthy'. "
        "End with one line noting this is a screening tool, not a diagnosis, and to consult a clinician.\n\n"
        "FACTS:\n" + json.dumps(facts, indent=2)
    )


# Deterministic Fallback And Mock

def render_template(facts):
    head = {
        "likely_pd": "This recording shows acoustic signs associated with Parkinson's.",
        "likely_healthy": "This recording shows no strong signs associated with Parkinson's.",
        "uncertain": "This result is borderline.",
    }[facts["band"]]
    factors = "; ".join(f"{f['concept']} ({f['direction']})" for f in facts["top_factors"])
    if facts["band"] == "uncertain":
        conf_line = "The signal was borderline, so this recording is flagged for follow-up rather than given a confident result."
    else:
        conf_line = f"The model is about {facts['stated_confidence_pct']}% confident in this reading."
    caution = " A 'no strong signs' result does not rule Parkinson's out." if facts["band"] == "likely_healthy" else ""
    return f"{head} {conf_line} The main contributing patterns were: {factors}.{caution} This is a screening signal, not a diagnosis; please consult a clinician."


def phrase_explanation(facts, llm_fn=None):
    if llm_fn is None:
        return render_template(facts)
    try:
        return llm_fn(build_prompt(facts))
    except Exception as error:
        print(f"LLM call failed ({error}); using template fallback.")
        return render_template(facts)


