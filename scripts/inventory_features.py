"""Build step 1: inventory the detector's feature columns, grouped by family.

Prints every column name the model expects, grouped by the dataset's own family
labels, and cross-checks that list against the ordered `feature_cols` stored in
the fitted model. Writes the same content to docs/feature_inventory.md.

    .venv/bin/python scripts/inventory_features.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from pdvoice import feature_spec  # noqa: E402

WRAP = 88


def _wrap_names(names: list[str], indent: str = "    ") -> list[str]:
    lines, current = [], indent
    for i, name in enumerate(names):
        piece = name + (", " if i < len(names) - 1 else "")
        if len(current) + len(piece) > WRAP and current.strip():
            lines.append(current.rstrip())
            current = indent
        current += piece
    if current.strip():
        lines.append(current.rstrip())
    return lines


def _model_feature_cols() -> list[str] | None:
    """Read the ordered `feature_cols` list out of the fitted model.

    Requires scikit-learn 1.6.1, the version the artifact was pickled under
    (see requirements.txt); newer versions cannot unpickle it at all.
    """
    path = feature_spec.REPO_ROOT / "models" / "detector_v1.joblib"
    if not path.exists():
        return None
    try:
        import joblib

        return list(joblib.load(path)["feature_cols"])
    except Exception as exc:  # pragma: no cover - diagnostic path
        print(f"  (could not read model feature_cols: {exc})", file=sys.stderr)
        return None


def build_report() -> str:
    families = feature_spec.load_families()
    feature_cols = feature_spec.load_feature_cols()
    implemented = set(feature_spec.implemented_feature_names())

    out: list[str] = []
    out.append("# Feature inventory — detector_v1")
    out.append("")
    out.append(
        "Generated by `scripts/inventory_features.py` from the training CSV's own "
        "two-row header. Do not hand-edit."
    )
    out.append("")
    out.append(f"Total model input features: **{len(feature_cols)}**")
    out.append("")

    out.append("## Summary")
    out.append("")
    out.append("| Family | Count | Implemented | Status |")
    out.append("|---|---:|---:|---|")
    for family, names in families.items():
        done = sum(1 for n in names if n in implemented)
        status = feature_spec.FAMILY_STATUS.get(
            family, "implemented (passed through)" if done == len(names) else "—"
        )
        out.append(f"| {family} | {len(names)} | {done} | {status} |")
    total_done = len(implemented)
    out.append(
        f"| **TOTAL** | **{len(feature_cols)}** | **{total_done}** "
        f"| {total_done / len(feature_cols):.0%} of columns |"
    )
    out.append("")

    out.append("## Columns by family")
    out.append("")
    for family, names in families.items():
        done = sum(1 for n in names if n in implemented)
        out.append(f"### {family} — {len(names)} columns ({done} implemented)")
        out.append("")
        out.append("```")
        out.extend(_wrap_names(names, indent=""))
        out.append("```")
        out.append("")

    out.append("## Cross-check against the fitted model")
    out.append("")
    model_cols = _model_feature_cols()
    if model_cols is None:
        out.append("Model artifact unavailable — CSV order assumed.")
    elif model_cols == feature_cols:
        out.append(
            f"OK — the {len(model_cols)} names and their order in "
            "`detector_v1.joblib` match the CSV exactly."
        )
    else:
        out.append("**MISMATCH** between model `feature_cols` and CSV columns:")
        out.append("")
        only_model = [c for c in model_cols if c not in set(feature_cols)]
        only_csv = [c for c in feature_cols if c not in set(model_cols)]
        out.append(f"- only in model: {only_model or 'none'}")
        out.append(f"- only in CSV: {only_csv or 'none'}")
        if not only_model and not only_csv:
            first = next(
                i for i, (a, b) in enumerate(zip(model_cols, feature_cols)) if a != b
            )
            out.append(f"- same names, different order; first divergence at index {first}")
    out.append("")

    out.append("## Still to reproduce")
    out.append("")
    missing = feature_spec.unimplemented_feature_names()
    out.append(
        f"{len(missing)} of {len(feature_cols)} features "
        f"({len(missing) / len(feature_cols):.0%}) are not yet extracted:"
    )
    out.append("")
    for family, names in families.items():
        gap = [n for n in names if n not in implemented]
        if gap:
            out.append(f"- **{family}** — {len(gap)} columns")
    out.append("")
    return "\n".join(out)


def main() -> int:
    report = build_report()
    print(report)

    dest = feature_spec.REPO_ROOT / "docs" / "feature_inventory.md"
    dest.parent.mkdir(exist_ok=True)
    dest.write_text(report)
    print(f"\n[written] {dest.relative_to(feature_spec.REPO_ROOT)}")

    # Sanity: the names we generate for MFCC must match the CSV literally.
    families = feature_spec.load_families()
    generated = feature_spec.mfcc_feature_names()
    if generated != families["MFCC"]:
        print("\nFATAL: generated MFCC names do not match the CSV.", file=sys.stderr)
        for gen, csv_name in zip(generated, families["MFCC"]):
            if gen != csv_name:
                print(f"  generated {gen!r} != csv {csv_name!r}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
